let viewerZoom = 1;

function renderImageViewer() {
  if (!imageViewerImage) return;
  imageViewerImage.style.setProperty("--viewer-width", `calc(min(1120px, 170vw) * ${viewerZoom})`);
}

function resetImageViewer() {
  viewerZoom = 1;
  renderImageViewer();
  requestAnimationFrame(() => {
    if (!imageViewerStage) return;
    imageViewerStage.scrollLeft = (imageViewerStage.scrollWidth - imageViewerStage.clientWidth) / 2;
    imageViewerStage.scrollTop = 0;
  });
}

function openImageViewer(src, alt) {
  if (!imageViewer || !imageViewerImage) return;
  imageViewerImage.src = src;
  imageViewerImage.alt = alt || "";
  resetImageViewer();
  imageViewer.hidden = false;
  document.body.classList.add("is-viewer-open");
}

function closeImageViewer() {
  if (!imageViewer || !imageViewerImage) return;
  imageViewer.hidden = true;
  imageViewerImage.src = "";
  document.body.classList.remove("is-viewer-open");
}

function setImageViewerZoom(nextZoom) {
  viewerZoom = Math.min(3, Math.max(1, nextZoom));
  renderImageViewer();
}

